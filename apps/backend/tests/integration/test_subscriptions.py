"""Integration tests for redeeming subscriptions.

These run against the real endpoint, a real database and a real signature check.
The only thing standing in for Apple is the root certificate the verifier
trusts, which is a key generated by the test rather than a bypass: a forged
transaction takes the same path a real one does and must still be refused.
"""

from __future__ import annotations

from datetime import UTC, datetime, timedelta
from typing import Any

import pytest
from fastapi import FastAPI
from httpx import ASGITransport, AsyncClient
from sqlalchemy import select

from tests.support.app_store import PRODUCT_ID, FakeAppStore, milliseconds, notification
from truvix.main import create_app
from truvix.modules.subscriptions.models import Entitlement, EntitlementStatus
from truvix.modules.subscriptions.router import get_verifier
from truvix.modules.subscriptions.verification import AppStoreVerifier
from truvix.modules.users.models import SubscriptionTier
from truvix.shared.config import Settings
from truvix.shared.container import ApplicationContainer

pytestmark = pytest.mark.integration

REGISTER_URL = "/api/v1/auth/register"
SUBSCRIPTIONS_URL = "/api/v1/subscriptions"
REDEEM_URL = "/api/v1/subscriptions/redeem"
NOTIFICATIONS_URL = "/api/v1/subscriptions/notifications"

_HTTP_OK = 200
_HTTP_CREATED = 201
_HTTP_UNAUTHORIZED = 401
_HTTP_CONFLICT = 409
_HTTP_UNPROCESSABLE = 422
_HTTP_NO_CONTENT = 204
_HTTP_UNAVAILABLE = 503

_PASSWORD = "a-sufficiently-long-passphrase"


@pytest.fixture
def app_store() -> FakeAppStore:
    """A stand-in App Store whose root the application will trust."""
    return FakeAppStore()


@pytest.fixture
async def client(
    settings: Settings, container: ApplicationContainer, app_store: FakeAppStore
) -> Any:
    """A client whose application trusts the stand-in store's root.

    Only the root is substituted. Every signature, certificate link and bundle
    check runs exactly as it does in production.
    """
    app = create_app(settings)
    app.state.container = container
    app.dependency_overrides[get_verifier] = lambda: AppStoreVerifier(
        root_certificates=[app_store.root.der],
        expected_bundle_id="app.truvix.ios",
    )
    transport = ASGITransport(app=app)
    async with AsyncClient(transport=transport, base_url="http://testserver") as http_client:
        yield http_client


@pytest.fixture
async def unconfigured_client(settings: Settings, container: ApplicationContainer) -> Any:
    """A client whose deployment cannot verify purchases at all."""
    app: FastAPI = create_app(settings)
    app.state.container = container
    transport = ASGITransport(app=app)
    async with AsyncClient(transport=transport, base_url="http://testserver") as http_client:
        yield http_client


async def _sign_up(client: AsyncClient, email: str) -> dict[str, str]:
    """Register an account and return its Authorization header."""
    response = await client.post(
        REGISTER_URL,
        json={"email": email, "password": _PASSWORD, "full_name": "Test Kullanici"},
    )
    assert response.status_code == _HTTP_CREATED, response.text
    return {"Authorization": f"Bearer {response.json()['tokens']['access_token']}"}


class TestRedeeming:
    """The happy path, which must actually change what the account can do."""

    async def test_a_verified_purchase_makes_the_account_premium(
        self, client: AsyncClient, app_store: FakeAppStore
    ) -> None:
        headers = await _sign_up(client, "buyer@truvix.app")

        response = await client.post(
            REDEEM_URL,
            json={"signed_transaction": app_store.transaction()},
            headers=headers,
        )

        assert response.status_code == _HTTP_OK, response.text
        body = response.json()
        assert body["tier"] == SubscriptionTier.PREMIUM.value
        assert body["is_premium"] is True
        assert len(body["entitlements"]) == 1
        assert body["entitlements"][0]["product_id"] == PRODUCT_ID
        assert body["entitlements"][0]["is_current"] is True

    async def test_the_new_plan_survives_into_the_next_request(
        self, client: AsyncClient, app_store: FakeAppStore
    ) -> None:
        """Premium must be persisted, not merely reported once."""
        headers = await _sign_up(client, "persists@truvix.app")
        await client.post(
            REDEEM_URL, json={"signed_transaction": app_store.transaction()}, headers=headers
        )

        response = await client.get(SUBSCRIPTIONS_URL, headers=headers)

        assert response.status_code == _HTTP_OK
        assert response.json()["tier"] == SubscriptionTier.PREMIUM.value

    async def test_a_new_account_starts_free_with_nothing(self, client: AsyncClient) -> None:
        headers = await _sign_up(client, "newcomer@truvix.app")

        response = await client.get(SUBSCRIPTIONS_URL, headers=headers)

        assert response.status_code == _HTTP_OK
        assert response.json() == {
            "tier": SubscriptionTier.FREE.value,
            "is_premium": False,
            "entitlements": [],
        }

    async def test_redeeming_the_same_purchase_twice_changes_nothing(
        self, client: AsyncClient, app_store: FakeAppStore
    ) -> None:
        """Restoring a purchase is normal and must not duplicate the entitlement."""
        headers = await _sign_up(client, "restorer@truvix.app")
        signed = app_store.transaction()

        await client.post(REDEEM_URL, json={"signed_transaction": signed}, headers=headers)
        response = await client.post(
            REDEEM_URL, json={"signed_transaction": signed}, headers=headers
        )

        assert response.status_code == _HTTP_OK
        assert len(response.json()["entitlements"]) == 1


class TestRefusals:
    """A transaction that does not verify must never grant anything."""

    async def test_a_forged_transaction_leaves_the_account_free(self, client: AsyncClient) -> None:
        """The attack that matters: a well-formed purchase somebody minted."""
        headers = await _sign_up(client, "forger@truvix.app")
        impostor = FakeAppStore()

        response = await client.post(
            REDEEM_URL,
            json={"signed_transaction": impostor.transaction()},
            headers=headers,
        )

        assert response.status_code == _HTTP_UNPROCESSABLE, response.text

        after = await client.get(SUBSCRIPTIONS_URL, headers=headers)
        assert after.json()["tier"] == SubscriptionTier.FREE.value
        assert after.json()["entitlements"] == []

    async def test_a_sandbox_purchase_is_refused(
        self, client: AsyncClient, app_store: FakeAppStore
    ) -> None:
        """Sandbox purchases are free; the deployment under test is production."""
        headers = await _sign_up(client, "sandboxer@truvix.app")

        response = await client.post(
            REDEEM_URL,
            json={"signed_transaction": app_store.transaction(environment="Sandbox")},
            headers=headers,
        )

        assert response.status_code == _HTTP_UNPROCESSABLE

    async def test_another_apps_purchase_is_refused(
        self, client: AsyncClient, app_store: FakeAppStore
    ) -> None:
        headers = await _sign_up(client, "wrongapp@truvix.app")

        response = await client.post(
            REDEEM_URL,
            json={"signed_transaction": app_store.transaction(bundleId="com.other.app")},
            headers=headers,
        )

        assert response.status_code == _HTTP_UNPROCESSABLE

    async def test_redeeming_requires_signing_in(
        self, client: AsyncClient, app_store: FakeAppStore
    ) -> None:
        response = await client.post(
            REDEEM_URL, json={"signed_transaction": app_store.transaction()}
        )

        assert response.status_code == _HTTP_UNAUTHORIZED

    async def test_reading_the_plan_requires_signing_in(self, client: AsyncClient) -> None:
        assert (await client.get(SUBSCRIPTIONS_URL)).status_code == _HTTP_UNAUTHORIZED

    async def test_an_unconfigured_deployment_refuses_rather_than_granting(
        self, unconfigured_client: AsyncClient, app_store: FakeAppStore
    ) -> None:
        """With no verifier there is no way to check, so nothing may be granted."""
        headers = await _sign_up(unconfigured_client, "unconfigured@truvix.app")

        response = await unconfigured_client.post(
            REDEEM_URL,
            json={"signed_transaction": app_store.transaction()},
            headers=headers,
        )

        assert response.status_code == _HTTP_UNAVAILABLE

        after = await unconfigured_client.get(SUBSCRIPTIONS_URL, headers=headers)
        assert after.json()["tier"] == SubscriptionTier.FREE.value


class TestOneSubscriptionOneAccount:
    """A single purchase must not entitle a crowd."""

    async def test_a_second_account_cannot_redeem_the_same_purchase(
        self, client: AsyncClient, app_store: FakeAppStore
    ) -> None:
        signed = app_store.transaction()
        first = await _sign_up(client, "owner@truvix.app")
        await client.post(REDEEM_URL, json={"signed_transaction": signed}, headers=first)

        second = await _sign_up(client, "freeloader@truvix.app")
        response = await client.post(
            REDEEM_URL, json={"signed_transaction": signed}, headers=second
        )

        assert response.status_code == _HTTP_CONFLICT, response.text

    async def test_the_freeloader_is_left_on_the_free_plan(
        self, client: AsyncClient, app_store: FakeAppStore
    ) -> None:
        signed = app_store.transaction()
        first = await _sign_up(client, "owner2@truvix.app")
        await client.post(REDEEM_URL, json={"signed_transaction": signed}, headers=first)

        second = await _sign_up(client, "freeloader2@truvix.app")
        await client.post(REDEEM_URL, json={"signed_transaction": signed}, headers=second)

        after = await client.get(SUBSCRIPTIONS_URL, headers=second)
        assert after.json()["tier"] == SubscriptionTier.FREE.value
        assert after.json()["entitlements"] == []

    async def test_the_rightful_owner_keeps_the_subscription(
        self, client: AsyncClient, app_store: FakeAppStore
    ) -> None:
        signed = app_store.transaction()
        first = await _sign_up(client, "owner3@truvix.app")
        await client.post(REDEEM_URL, json={"signed_transaction": signed}, headers=first)

        second = await _sign_up(client, "freeloader3@truvix.app")
        await client.post(REDEEM_URL, json={"signed_transaction": signed}, headers=second)

        after = await client.get(SUBSCRIPTIONS_URL, headers=first)
        assert after.json()["tier"] == SubscriptionTier.PREMIUM.value


class TestSubscriptionLifecycle:
    """What the App Store reports later must actually take effect."""

    async def test_an_expired_subscription_does_not_grant_premium(
        self, client: AsyncClient, app_store: FakeAppStore
    ) -> None:
        """An expiry in the past must not be honoured even with an active status."""
        headers = await _sign_up(client, "lapsed@truvix.app")
        past = datetime.now(UTC) - timedelta(days=1)

        response = await client.post(
            REDEEM_URL,
            json={
                "signed_transaction": app_store.transaction(
                    purchaseDate=milliseconds(past - timedelta(days=30)),
                    expiresDate=milliseconds(past),
                )
            },
            headers=headers,
        )

        assert response.status_code == _HTTP_OK, response.text
        assert response.json()["tier"] == SubscriptionTier.FREE.value
        assert response.json()["entitlements"][0]["is_current"] is False

    async def test_a_renewal_extends_the_subscription(
        self, client: AsyncClient, app_store: FakeAppStore
    ) -> None:
        headers = await _sign_up(client, "renewer@truvix.app")
        now = datetime.now(UTC)

        await client.post(
            REDEEM_URL,
            json={
                "signed_transaction": app_store.transaction(
                    purchaseDate=milliseconds(now - timedelta(days=30)),
                    expiresDate=milliseconds(now + timedelta(minutes=1)),
                )
            },
            headers=headers,
        )
        response = await client.post(
            REDEEM_URL,
            json={
                "signed_transaction": app_store.transaction(
                    transactionId="2000000891234568",
                    purchaseDate=milliseconds(now),
                    expiresDate=milliseconds(now + timedelta(days=30)),
                )
            },
            headers=headers,
        )

        assert response.status_code == _HTTP_OK
        assert len(response.json()["entitlements"]) == 1
        assert response.json()["tier"] == SubscriptionTier.PREMIUM.value

    async def test_a_late_arriving_older_transaction_does_not_undo_a_renewal(
        self, client: AsyncClient, app_store: FakeAppStore
    ) -> None:
        """Apple can deliver out of order; a stale one must not cancel a live plan."""
        headers = await _sign_up(client, "outoforder@truvix.app")
        now = datetime.now(UTC)

        renewal = app_store.transaction(
            transactionId="2000000891234569",
            purchaseDate=milliseconds(now),
            expiresDate=milliseconds(now + timedelta(days=30)),
        )
        stale = app_store.transaction(
            purchaseDate=milliseconds(now - timedelta(days=30)),
            expiresDate=milliseconds(now - timedelta(days=1)),
        )

        await client.post(REDEEM_URL, json={"signed_transaction": renewal}, headers=headers)
        response = await client.post(
            REDEEM_URL, json={"signed_transaction": stale}, headers=headers
        )

        assert response.status_code == _HTTP_OK
        assert response.json()["tier"] == SubscriptionTier.PREMIUM.value
        assert response.json()["entitlements"][0]["is_current"] is True

    async def test_a_revoked_purchase_takes_premium_away(
        self, client: AsyncClient, app_store: FakeAppStore
    ) -> None:
        """A refund must not leave the account premium."""
        headers = await _sign_up(client, "refunded@truvix.app")
        now = datetime.now(UTC)

        await client.post(
            REDEEM_URL, json={"signed_transaction": app_store.transaction()}, headers=headers
        )
        response = await client.post(
            REDEEM_URL,
            json={
                "signed_transaction": app_store.transaction(
                    transactionId="2000000891234570",
                    purchaseDate=milliseconds(now + timedelta(seconds=1)),
                    revocationDate=milliseconds(now),
                    status=5,
                )
            },
            headers=headers,
        )

        assert response.status_code == _HTTP_OK, response.text
        assert response.json()["tier"] == SubscriptionTier.FREE.value

    async def test_a_billing_retry_keeps_the_customer_premium(
        self, client: AsyncClient, app_store: FakeAppStore
    ) -> None:
        """Apple is retrying a card; removing features here loses the customer."""
        headers = await _sign_up(client, "retrying@truvix.app")

        response = await client.post(
            REDEEM_URL,
            json={"signed_transaction": app_store.transaction(status=3)},
            headers=headers,
        )

        assert response.status_code == _HTTP_OK
        assert response.json()["tier"] == SubscriptionTier.PREMIUM.value


class TestPersistedState:
    """What ends up in the database has to match what was reported."""

    async def test_the_entitlement_records_what_apple_signed(
        self, client: AsyncClient, app_store: FakeAppStore, session: Any
    ) -> None:
        headers = await _sign_up(client, "recorded@truvix.app")
        await client.post(
            REDEEM_URL, json={"signed_transaction": app_store.transaction()}, headers=headers
        )

        entitlement = await session.scalar(
            select(Entitlement).where(Entitlement.original_transaction_id == "2000000891234567")
        )

        assert entitlement is not None
        assert entitlement.product_id == PRODUCT_ID
        assert entitlement.status is EntitlementStatus.ACTIVE
        assert entitlement.expires_at is not None


class TestStoreNotifications:
    """Refunds and cancellations only reach us through this endpoint."""

    async def test_a_refund_takes_premium_away_without_the_app_involved(
        self, client: AsyncClient, app_store: FakeAppStore
    ) -> None:
        """The customer has their money back; they must not keep the features."""
        headers = await _sign_up(client, "refund-webhook@truvix.app")
        await client.post(
            REDEEM_URL, json={"signed_transaction": app_store.transaction()}, headers=headers
        )
        now = datetime.now(UTC)

        response = await client.post(
            NOTIFICATIONS_URL,
            json={
                "signedPayload": notification(
                    app_store,
                    "REFUND",
                    transactionId="2000000891234571",
                    purchaseDate=milliseconds(now + timedelta(seconds=1)),
                    revocationDate=milliseconds(now),
                    status=5,
                )
            },
        )

        assert response.status_code == _HTTP_NO_CONTENT, response.text

        after = await client.get(SUBSCRIPTIONS_URL, headers=headers)
        assert after.json()["tier"] == SubscriptionTier.FREE.value

    async def test_a_renewal_notification_extends_the_subscription(
        self, client: AsyncClient, app_store: FakeAppStore
    ) -> None:
        headers = await _sign_up(client, "renew-webhook@truvix.app")
        now = datetime.now(UTC)
        await client.post(
            REDEEM_URL,
            json={
                "signed_transaction": app_store.transaction(
                    purchaseDate=milliseconds(now - timedelta(days=30)),
                    expiresDate=milliseconds(now + timedelta(minutes=1)),
                )
            },
            headers=headers,
        )

        response = await client.post(
            NOTIFICATIONS_URL,
            json={
                "signedPayload": notification(
                    app_store,
                    "DID_RENEW",
                    transactionId="2000000891234572",
                    purchaseDate=milliseconds(now),
                    expiresDate=milliseconds(now + timedelta(days=30)),
                )
            },
        )

        assert response.status_code == _HTTP_NO_CONTENT
        after = await client.get(SUBSCRIPTIONS_URL, headers=headers)
        assert after.json()["tier"] == SubscriptionTier.PREMIUM.value

    async def test_a_forged_notification_is_refused(
        self, client: AsyncClient, app_store: FakeAppStore
    ) -> None:
        """The endpoint takes no token, so the signature must carry the whole load."""
        headers = await _sign_up(client, "webhook-forgery@truvix.app")
        await client.post(
            REDEEM_URL, json={"signed_transaction": app_store.transaction()}, headers=headers
        )
        impostor = FakeAppStore()

        response = await client.post(
            NOTIFICATIONS_URL,
            json={"signedPayload": notification(impostor, "REFUND", status=5)},
        )

        assert response.status_code == _HTTP_UNPROCESSABLE

        after = await client.get(SUBSCRIPTIONS_URL, headers=headers)
        assert after.json()["tier"] == SubscriptionTier.PREMIUM.value

    async def test_a_genuine_envelope_around_a_forged_transaction_is_refused(
        self, client: AsyncClient, app_store: FakeAppStore
    ) -> None:
        """Both signatures are checked, not just the outer one."""
        impostor = FakeAppStore()
        envelope = app_store.sign(
            {
                "notificationType": "REFUND",
                "notificationUUID": "6b1f0f5e-1f34-4f0a-92f2-52f6a0c1c3d1",
                "data": {
                    "bundleId": "app.truvix.ios",
                    "environment": "Production",
                    "signedTransactionInfo": impostor.transaction(status=5),
                },
            }
        )

        response = await client.post(NOTIFICATIONS_URL, json={"signedPayload": envelope})

        assert response.status_code == _HTTP_UNPROCESSABLE

    async def test_a_notification_for_an_unknown_subscription_is_accepted_quietly(
        self, client: AsyncClient, app_store: FakeAppStore
    ) -> None:
        """Refusing would make Apple retry something that can never succeed."""
        response = await client.post(
            NOTIFICATIONS_URL,
            json={
                "signedPayload": notification(
                    app_store, "DID_RENEW", originalTransactionId="9999999999999999"
                )
            },
        )

        assert response.status_code == _HTTP_NO_CONTENT

    async def test_an_envelope_carrying_no_transaction_is_refused(
        self, client: AsyncClient, app_store: FakeAppStore
    ) -> None:
        envelope = app_store.sign({"notificationType": "TEST", "data": {}})

        response = await client.post(NOTIFICATIONS_URL, json={"signedPayload": envelope})

        assert response.status_code == _HTTP_UNPROCESSABLE
